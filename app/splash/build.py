"""Builds the console's start animations (static/splash.css, static/splash-data.js) from the standalone pages here.

Each NN-name.html is one animation as designed (by the Codex session, on logo 05 "Gravure croisée"): its own <style>,
its SVG scene, the name and a status line. The console's pages allow no inline style and no frame (its CSP), so they
are taken apart: every rule is scoped under `.sa-aNN` (the element that holds the scene), every @keyframes renamed
`aNN-…` (they all live in one stylesheet), `style` attributes kept as `data-sa-style` (applied by script, through the
CSSOM), and the texts put in English. Run it after adding, removing or changing a page here:

    python3 app/splash/build.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
STATIC = HERE.parent / "static"
STATUS = "Connecting to services…"  # as many characters as the original line: the typing animation steps on them


def blocks(css: str):
    """The top-level blocks of a stylesheet: (prelude, body)."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield css[i:j].strip(), css[j + 1:k - 1]
        i = k


def scope_selector(sel: str, scope: str) -> str:
    sel = sel.strip()
    if sel in ("html", "body"):
        return scope
    if sel.startswith("body"):
        return scope + sel[4:]
    return f"{scope} {sel.replace('.splash', '.sa-main')}"


def rename_animations(body: str, names: dict[str, str]) -> str:
    def fix(m):
        return m.group(1) + re.sub(r"[\w-]+", lambda w: names.get(w.group(0), w.group(0)), m.group(2))
    return re.sub(r"(animation(?:-name)?\s*:)([^;}]*)", fix, body)


def scope_css(css: str, scope: str, names: dict[str, str]) -> str:
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith("@keyframes"):
            out.append(f"@keyframes {names[prelude.split()[1]]}{{{body}}}")
        elif prelude.startswith("@media"):
            out.append(f"{prelude}{{{scope_css(body, scope, names)}}}")
        else:
            sels = ",".join(scope_selector(s, scope) for s in prelude.split(","))
            out.append(f"{sels}{{{rename_animations(body, names)}}}")
    return "".join(out)


def build() -> tuple[str, list[dict]]:
    css, anims = [], []
    for page in sorted(HERE.glob("[0-9][0-9]-*.html")):
        h = page.read_text(encoding="utf-8")
        n = page.name[:2]
        style = re.search(r"<style>(.*?)</style>", h, re.S).group(1)
        dur = float(re.search(r'<body[^>]*style="--duration:([\d.]+)s"', h).group(1))
        names = {k: f"a{n}-{k}" for k in re.findall(r"@keyframes\s+([\w-]+)", style)}
        css.append(f"/* {page.name} */\n" + scope_css(style, f".sa-a{n}", names))
        m = re.search(r"<main class=\"splash\"[^>]*>(.*?)</main>", h, re.S).group(1)
        m = re.sub(r'\sstyle="', ' data-sa-style="', m)
        m = m.replace("<h1 ", "<div ").replace("</h1>", "</div>")
        m = m.replace("Connexion aux services…", STATUS)
        m = re.sub(r'aria-label="Logo mmbox[^"]*"', 'aria-label="mmbox logo"', m)
        if re.search(r"[àâçéèêëîïôûùüÿœ]", re.sub(r"<[^>]*>", "", m)):
            raise SystemExit(f"{page.name}: French text left in it")
        anims.append({"n": n, "name": page.stem[3:], "d": dur, "html": f'<div class="sa-main">{m}</div>'})
    return "\n".join(css) + "\n", anims


def main() -> None:
    css, anims = build()
    head = "/* Generated by app/splash/build.py from app/splash/*.html: edit those, then run it. */\n"
    (STATIC / "splash.css").write_text(head + css, encoding="utf-8")
    (STATIC / "splash-data.js").write_text(
        head + "window.MMBOX_SPLASH = " + json.dumps(anims, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    print(f"{len(anims)} animations: {', '.join(a['n'] for a in anims)} -> static/splash.css, static/splash-data.js")


if __name__ == "__main__":
    main()
